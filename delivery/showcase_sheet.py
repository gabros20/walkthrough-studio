#!/usr/bin/env python3
"""A showcase sheet: justified rows of creatives that respect each format's shape, with a branded header.

usage: python3 -I delivery/showcase_sheet.py SHEET.json OUT.png [--jpg]

SHEET.json:
{
  "size": [3840, 2160],                       # 16:9 slide; A3 landscape at 300 dpi is [4961, 3508]
  "brand": {"accent": "#0E7C86", "ink": "#141414", "paper": "#F4F2EE",
            "font": "/path/Roboto-Bold.ttf", "font_regular": "/path/Roboto-Regular.ttf",
            "logo": "/path/brand-logo-black.png"},
  "eyebrow": "Creative showcase",
  "title": "One option, 18 formats",
  "caption": "Every size is laid out again for its own shape, not cropped from one master.",
  "footer": "Generated by the app from the brand hub. The shop shown is fictional.",
  "rows": [["a.jpg", "b.jpg", "c.jpg"], ["d.jpg", "e.jpg"]],   # or "images": [...] for automatic rows
  "labels": {"a.jpg": "Instagram · Feed 1:1"},                 # optional, drawn under each tile
  "max_upscale": 2.0                                           # tiles never exceed their own pixels by more
}
Order and grouping are design decisions: give explicit "rows" for a sheet that makes a point (e.g. tall
formats together, banners together); "images" sorts by shape (unless "sort": false) and picks the row count that gives the largest tiles.
Paths in SHEET.json resolve against its folder. The real logo file is pasted, never redrawn.
For HTML-quality typography render an HTML layout with Playwright instead (examples/brightpost/delivery
describes how the real sheets were made); this script is the dependable Pillow-only route.
"""
import json
import os
import sys

from PIL import Image, ImageDraw, ImageFont

DEFAULT = {"accent": "#0E7C86", "ink": "#141414", "paper": "#F4F2EE"}


def font(path, size, fallback_bold=True):
    for p in [path, "/System/Library/Fonts/Supplemental/Arial Bold.ttf" if fallback_bold else "/System/Library/Fonts/Supplemental/Arial.ttf",
              "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"]:
        if p and os.path.exists(p):
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()


def split_rows(paths, ars, n):
    """Split images (in order) into n rows of roughly equal summed aspect ratio."""
    target = sum(ars) / n
    rows, row, acc = [], [], 0.0
    for p, ar in zip(paths, ars):
        if row and acc + ar / 2 > target and len(rows) < n - 1:
            rows.append(row)
            row, acc = [], 0.0
        row.append(p)
        acc += ar
    rows.append(row)
    return rows


def layout(rows, ims, avail_w, avail_h, gap, lab_h):
    """Row heights for justified rows filling avail_w, then one scale k so the stack (with its fixed gaps and
    label lines) fits avail_h. Returns (heights, k, stacked height after scaling)."""
    heights = [(avail_w - gap * (len(r) - 1)) / sum(ims[p].width / ims[p].height for p in r) for r in rows]
    fixed = (gap + lab_h) * len(rows) - gap
    k = min(1.0, max(0.01, (avail_h - fixed) / sum(heights)))
    return heights, k, sum(heights) * k + fixed


def best_rows(paths, ims, avail_w, avail_h, gap, lab_h, cap):
    """Try 1..n rows; keep the split whose tiles cover the most area (after the upscale cap)."""
    ars = [ims[p].width / ims[p].height for p in paths]
    best = None
    for n in range(1, len(paths) + 1):
        rows = split_rows(paths, ars, n)
        heights, k, _ = layout(rows, ims, avail_w, avail_h, gap, lab_h)
        area = sum(min(h * k, min(ims[p].height for p in r) * cap) ** 2 * sum(ims[p].width / ims[p].height for p in r)
                   for r, h in zip(rows, heights))
        if best is None or area > best[0]:
            best = (area, rows)
    return best[1]


def main():
    if any(x in ("-h", "--help") for x in sys.argv[1:]):
        print(__doc__.strip())
        sys.exit(0)
    if len(sys.argv) < 3:
        print(__doc__)
        sys.exit(1)
    spec_path, out = sys.argv[1], sys.argv[2]
    base = os.path.dirname(os.path.abspath(spec_path))
    S = json.load(open(spec_path, encoding="utf-8"))
    rp = lambda p: p if os.path.isabs(p) else os.path.join(base, p)
    W, H = S.get("size", [3840, 2160])
    b = {**DEFAULT, **S.get("brand", {})}
    u = W / 1600  # scale unit
    m = round(W * 0.042)
    gap = round(18 * u)
    lab_h = round(26 * u) if S.get("labels") else 0
    sheet = Image.new("RGB", (W, H), b["paper"])
    d = ImageDraw.Draw(sheet)

    # header: logo left, eyebrow right, accent rule, title, caption
    if b.get("logo") and os.path.exists(rp(b["logo"])):
        logo = Image.open(rp(b["logo"])).convert("RGBA")
        lw = round(112 * u)
        logo = logo.resize((lw, round(logo.height * lw / logo.width)), Image.LANCZOS)
        sheet.paste(logo, (m, m), logo)
    if S.get("eyebrow"):
        f = font(b.get("font"), round(13 * u))
        txt = S["eyebrow"].upper()
        d.text((W - m - d.textlength(txt, font=f), m + round(6 * u)), txt, fill=b["accent"], font=f)
    ty = m + round(58 * u)
    d.rectangle([m, ty, m + round(44 * u), ty + max(4, round(4 * u))], fill=b["accent"])
    d.text((m, ty + round(14 * u)), S.get("title", ""), fill=b["ink"], font=font(b.get("font"), round(44 * u)))
    if S.get("caption"):
        d.text((m, ty + round(70 * u)), S["caption"], fill=b["ink"], font=font(b.get("font_regular"), round(18 * u), False))
    top = ty + round(118 * u)
    fb = H - m - round(30 * u)
    d.line([m, fb, W - m, fb], fill="#C9C6C1", width=max(1, round(u)))
    if S.get("footer"):
        d.text((m, fb + round(10 * u)), S["footer"], fill="#77746F", font=font(b.get("font_regular"), round(11.5 * u), False))
    bottom = fb - round(26 * u)

    # tiles: justified rows that fill the width, then scaled down together to fit the height;
    # with "images" (no explicit rows) the row count that gives the largest tiles is chosen
    avail_w = W - 2 * m
    if "rows" in S:
        rows = [[rp(p) for p in r] for r in S["rows"]]
        ims = {p: Image.open(p).convert("RGB") for r in rows for p in r}
    else:
        paths = [rp(p) for p in S["images"]]
        ims = {p: Image.open(p).convert("RGB") for p in paths}
        if S.get("sort", True):  # group similar shapes so banners and squares do not share a row
            paths.sort(key=lambda p: ims[p].width / ims[p].height)
        rows = best_rows(paths, ims, avail_w, bottom - top, gap, lab_h, S.get("max_upscale", 2.0))
    heights, k, total = layout(rows, ims, avail_w, bottom - top, gap, lab_h)
    y = top + ((bottom - top) - total) / 2
    labels = {rp(p): t for p, t in S.get("labels", {}).items()}
    lf = font(b.get("font_regular"), round(12 * u), False)
    cap = S.get("max_upscale", 2.0)  # never blow a small banner up past this factor of its own pixels
    for r, h in zip(rows, heights):
        slot = h * k
        h = min(slot, min(ims[p].height for p in r) * cap)
        y_row = y + (slot - h) / 2
        row_w = sum(ims[p].width / ims[p].height * h for p in r) + gap * (len(r) - 1)
        x = m + (avail_w - row_w) / 2
        for p in r:
            w = ims[p].width / ims[p].height * h
            tile = ims[p].resize((round(w), round(h)), Image.LANCZOS)
            sheet.paste(tile, (round(x), round(y_row)))
            d.rectangle([round(x), round(y_row), round(x + w) - 1, round(y_row + h) - 1], outline="#D8D5D0", width=max(1, round(u / 2)))
            if p in labels:
                t = labels[p]
                while t and d.textlength(t, font=lf) > w + gap * 0.8:
                    t = t[:-2] + "…" if len(t) > 2 else ""
                d.text((round(x), round(y_row + h + 6 * u)), t, fill="#5A5854", font=lf)
            x += w + gap
        y += slot + gap + lab_h
    sheet.save(out, optimize=True)
    if "--jpg" in sys.argv:
        sheet.save(os.path.splitext(out)[0] + ".jpg", quality=88)
    print(out, f"{W}x{H}", f"{sum(len(r) for r in rows)} tiles in {len(rows)} rows")


if __name__ == "__main__":
    main()
