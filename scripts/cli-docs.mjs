#!/usr/bin/env node
// Rewrites the "Usage of every command" block of docs/CLI.md from `walkthrough help --all`, so the
// reference always quotes each command file's own `usage` export.
//   node scripts/cli-docs.mjs          write docs/CLI.md
//   node scripts/cli-docs.mjs --check  exit 1 when docs/CLI.md is out of date (writes nothing)
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOC = join(ROOT, "docs", "CLI.md");
const BEGIN = "<!-- walkthrough help --all: begin (generated by scripts/cli-docs.mjs; do not edit by hand) -->";
const END = "<!-- walkthrough help --all: end -->";
// Run from the kit's parent folder so no project is resolved and the output does not depend on cwd.
const r = spawnSync(process.execPath, [join(ROOT, "bin", "walkthrough.mjs"), "help", "--all"], { cwd: "/", encoding: "utf8", env: { ...process.env, WALKTHROUGH_PROJECT: "" } });
if (r.status !== 0 || r.stderr.includes("skipped")) {
  console.error(`walkthrough help --all failed or skipped a command:\n${r.stderr}`);
  process.exit(1);
}
const doc = readFileSync(DOC, "utf8");
const i = doc.indexOf(BEGIN);
const j = doc.indexOf(END);
if (i < 0 || j < i) {
  console.error(`docs/CLI.md has no ${BEGIN} … ${END} block`);
  process.exit(1);
}
const next = `${doc.slice(0, i + BEGIN.length)}\n\n${r.stdout.trim()}\n\n${doc.slice(j)}`;
if (process.argv.includes("--check")) {
  if (next !== doc) {
    console.error("docs/CLI.md is out of date: run node scripts/cli-docs.mjs");
    process.exit(1);
  }
  console.log("docs/CLI.md is up to date");
} else {
  writeFileSync(DOC, next);
  console.log(next === doc ? "docs/CLI.md already up to date" : "docs/CLI.md: usage block rewritten");
}
