// A film project: the folder that holds one film's inputs (storyboard.json, brand.json,
// creatives.json, music.json, voiceover/) and receives every output (index.html, compositions/,
// assets/, cues.json, edl.json, captions.srt, renders/, sound-build/). It is a HyperFrames project
// of its own, so `npx hyperframes@0.9.16 check` / `render` run inside it. The kit (this film/
// folder, possibly a read-only plugin cache) is code only and is never written to during use;
// running inside the kit's film/ itself is the development case.
//
// ensureProject(dir) writes the HyperFrames project files a project needs when they are missing
// (never overwrites): hyperframes.json, meta.json, package.json (pinned hyperframes scripts),
// CLAUDE.md + AGENTS.md (the HyperFrames instructions), .gitignore, kit.json (where the kit is),
// compositions/.

import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const KIT_FILM_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const HYPERFRAMES = "hyperframes@0.9.16";

const GITIGNORE = `# generated by the kit's build.mjs / build-demo.mjs: edit the storyboard or the brand, not these
index.html
compositions/*.html
cues.json
captions.srt
edl.json
# media: footage cuts, synced brand and creative files, audio, renders, review frames
assets/footage/
assets/brand/
assets/creatives/
assets/audio/
renders/
review/
sound-build/
# tools
.hyperframes/
node_modules/
.DS_Store
`;

/** Write the missing HyperFrames project files into dir. Returns the list of files written. */
export function ensureProject(dir) {
  dir = resolve(dir);
  if (dir === KIT_FILM_DIR) return []; // developing inside the kit: its own files are already there
  mkdirSync(join(dir, "compositions"), { recursive: true });
  const wrote = [];
  const put = (name, content) => {
    const p = join(dir, name);
    if (existsSync(p)) return;
    if (typeof content === "function") content(p);
    else writeFileSync(p, content);
    wrote.push(name);
  };
  const name = basename(dir).replace(/[^\w.-]+/g, "-").toLowerCase() || "film";
  put("hyperframes.json", (p) => copyFileSync(join(KIT_FILM_DIR, "hyperframes.json"), p));
  put("meta.json", JSON.stringify({ id: name, name }, null, 2) + "\n");
  put("package.json", JSON.stringify({
    name, private: true, type: "module",
    scripts: {
      dev: `npx --yes ${HYPERFRAMES} preview`,
      check: `npx --yes ${HYPERFRAMES} check`,
      render: `npx --yes ${HYPERFRAMES} render`,
      publish: `npx --yes ${HYPERFRAMES} publish`,
    },
  }, null, 2) + "\n");
  put("CLAUDE.md", (p) => copyFileSync(join(KIT_FILM_DIR, "CLAUDE.md"), p));
  put("AGENTS.md", (p) => copyFileSync(join(KIT_FILM_DIR, "AGENTS.md"), p));
  put(".gitignore", GITIGNORE);
  put("compositions/.gitkeep", "");
  // where the kit is, so a later session (or a wrapper) finds the build scripts again
  const kitJson = join(dir, "kit.json");
  const kit = { film: KIT_FILM_DIR, build: join(KIT_FILM_DIR, "build.mjs"), sound: resolve(KIT_FILM_DIR, "../sound/build-sound.mjs"), hyperframes: HYPERFRAMES };
  const old = existsSync(kitJson) ? readFileSync(kitJson, "utf8") : null;
  const now = JSON.stringify(kit, null, 2) + "\n";
  if (old !== now) { writeFileSync(kitJson, now); if (!old) wrote.push("kit.json"); }
  return wrote;
}
