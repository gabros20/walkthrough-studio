// Builds the site's animated visuals as HyperFrames projects, one folder per visual:
//   hero/  pipeline/  twins/  audit/
// Each is made from the kit's own film components (film/lib: stage, pointer, camera, captions, tag,
// emit), over a mock web app drawn as HTML instead of recorded footage (lib/mockapp.mjs).
//
//   node build.mjs [hero|pipeline|twins|audit]...     # default: all
//   (cd hero && npx --yes hyperframes@0.9.16 check --json)
//   ./render.sh                                        # render + encode into ../public/visuals/
//
// The palette and type come from ../DESIGN.md via brand.json (read by film/lib/config.mjs).

import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
// film/lib/config.mjs reads these when it is first imported: brand.json from here, 30 fps.
process.env.FILM_PROJECT = HERE;
process.env.FILM_FPS = process.env.FILM_FPS || "30";

const want = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const all = ["hero", "pipeline", "twins", "audit"];
const { FILM, COLOR } = await import("../../film/lib/config.mjs");
const { n } = await import("../../film/lib/emit.mjs");

export const FONT_FACE = `@font-face { font-family: "Archivo"; src: url("assets/fonts/Archivo.woff2") format("woff2"); font-weight: 100 900; font-stretch: 62% 125%; font-display: block; }`;

/** Put the Archivo face into a scene file's <style>. */
const withFont = (src) => src.replace("<style>", `<style>\n    ${FONT_FACE}`);

function writeProject(name, { duration, scenes }) {
  const dir = join(HERE, name);
  mkdirSync(join(dir, "compositions"), { recursive: true });
  mkdirSync(join(dir, "assets/fonts"), { recursive: true });
  copyFileSync(join(HERE, "fonts/Archivo.woff2"), join(dir, "assets/fonts/Archivo.woff2"));
  writeFileSync(join(dir, "hyperframes.json"), JSON.stringify({ $schema: "https://hyperframes.heygen.com/schema/hyperframes.json", paths: { blocks: "compositions", assets: "assets" }, authoringSkill: "hyperframes" }, null, 2) + "\n");
  writeFileSync(join(dir, "meta.json"), JSON.stringify({ id: `site-${name}`, name: `site-${name}` }, null, 2) + "\n");
  for (const s of scenes) writeFileSync(join(dir, `compositions/${s.id}.html`), withFont(s.file));
  const host = (s, z) =>
    `      <div id="${s.id}" data-composition-id="${s.id}" data-composition-src="compositions/${s.id}.html" data-start="${n(s.start ?? 0)}" data-duration="${n(s.duration ?? duration)}" data-track-index="${z}" data-track-kind="${s.kind ?? "graphics"}" data-width="${FILM.width}" data-height="${FILM.height}" style="z-index:${z}"></div>`;
  writeFileSync(
    join(dir, "index.html"),
    `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${FILM.width}, height=${FILM.height}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <style>
      ${FONT_FACE}
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: ${FILM.width}px; height: ${FILM.height}px; overflow: hidden; background: ${COLOR.ink}; }
      #root { position: relative; width: 100%; height: 100%; background: ${COLOR.ink}; }
    </style>
  </head>
  <body>
    <!-- Generated by site/visuals-src/build.mjs (${name}). Edit the builder, not this file. -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="${n(duration)}" data-fps="${FILM.fps}" data-width="${FILM.width}" data-height="${FILM.height}">
${scenes.map((s, i) => host(s, i + 1)).join("\n")}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`,
  );
  console.log(`${name}: ${n(duration)} s @ ${FILM.fps} fps, scenes ${scenes.map((s) => s.id).join(", ")}`);
}

for (const name of want.length ? want : all) {
  const mod = await import(`./comps/${name}.mjs`);
  writeProject(name, await mod.build());
}
